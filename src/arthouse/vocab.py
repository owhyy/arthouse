"""Closed, cross-media descriptor vocabulary.

One flat list of ~220 descriptors, each belonging to exactly one of six facets.
A descriptor describes *what a work is like* in a way that an album, a film and
a book can all share; anything that only makes sense for one medium (audio
production, vocal technique, release metadata) is deliberately absent.

Two relations are recorded per descriptor:

`aliases`
    The same concept under a different form ("melancholy", "sad", "sorrowful").
    Any raw provider tag that normalises to an alias is *tagged* with the
    descriptor. An alias belongs to exactly one descriptor.

`neighbors`
    Different but adjacent concepts ("sombre", "bittersweet" for "melancholic").
    Neighbours never tag anything; they exist so a query for one descriptor can
    later widen to its surroundings.

Matching is exact after `normalize()`: no stemming, no edit distance, no model.
That is deliberate — see the rejected `poison`/`prison` and `angel`/`anger`
merges in the project log. Unmapped tags are dropped and reported by
`arthouse.tagging`, never guessed at.
"""

import re
import unicodedata
from dataclasses import dataclass
from enum import StrEnum


class Facet(StrEnum):
    MOOD = "mood"
    TONE = "tone"
    ATMOSPHERE = "atmosphere"
    SETTING = "setting"
    THEME = "theme"
    STYLE = "style"
    CREATOR = "creator"


FACETS: tuple[Facet, ...] = tuple(Facet)

_PARENTHETICAL = re.compile(r"\([^)]*\)")
_WHITESPACE = re.compile(r"\s+")
_SEPARATORS = re.compile(r"[-_/.\u2010-\u2015]")
_APOSTROPHE = re.compile(r"['\u2019]")
_NON_WORD = re.compile(r"[^\w\s]")


def normalize(text: str) -> str:
    """Lookup key for a tag or alias.

    Folds case, strips parentheticals and punctuation, turns dashes and
    underscores into spaces, and collapses whitespace, so "Sci-Fi",
    "sci fi" and "Science Fiction (genre)" all reach one entry instead of
    three. Pure and idempotent.
    """
    text = unicodedata.normalize("NFC", text).casefold()
    stripped = _PARENTHETICAL.sub(" ", text)
    if stripped.strip():
        text = stripped
    text = text.replace("&", " and ")
    text = _APOSTROPHE.sub("", text)
    text = _SEPARATORS.sub(" ", text)
    text = _NON_WORD.sub(" ", text)
    return _WHITESPACE.sub(" ", text).strip()


