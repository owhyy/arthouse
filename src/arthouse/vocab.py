def _build_index() -> tuple[dict[str, Descriptor], dict[str, Descriptor]]:
    """Validate the vocabulary and build the name and alias lookups.

    Every failure here is an authoring mistake in this file, so it raises at
    import: a duplicate alias or a dangling neighbour should break the build,
    not silently swallow tags at runtime.
    """
    by_name: dict[str, Descriptor] = {}
    for descriptor in DESCRIPTORS:
        key = normalize(descriptor.name)
        if not key:
            raise ValueError(f"descriptor {descriptor.name!r} normalises to nothing")
        if descriptor.facet not in FACETS:
            raise ValueError(f"{descriptor.name!r} has unknown facet {descriptor.facet!r}")
        if key in by_name:
            raise ValueError(f"duplicate descriptor name {descriptor.name!r}")
        by_name[key] = descriptor

    by_alias: dict[str, Descriptor] = {}
    for descriptor in DESCRIPTORS:
        for alias in descriptor.aliases:
            key = normalize(alias)
            if not key:
                raise ValueError(f"{descriptor.name!r} has an empty alias {alias!r}")
            # An alias that folds onto its own name ("self hatred" for
            # "self-hatred") is a harmless no-op; landing on a *different*
            # descriptor's name is always a mistake.
            owner = by_name.get(key)
            if owner is not None and owner is not descriptor:
                raise ValueError(
                    f"alias {alias!r} of {descriptor.name!r} collides with a descriptor name"
                )
            if key in by_alias:
                other = by_alias[key].name
                raise ValueError(
                    f"alias {alias!r} is claimed by both {other!r} and {descriptor.name!r}"
                )
            by_alias[key] = descriptor

    for descriptor in DESCRIPTORS:
        for neighbor in descriptor.neighbors:
            if normalize(neighbor) not in by_name:
                raise ValueError(f"{descriptor.name!r} has unknown neighbour {neighbor!r}")

    return by_name, by_alias


_BY_NAME, _BY_ALIAS = _build_index()


def lookup(tag: str) -> Descriptor | None:
    """The descriptor a raw tag maps to, or None when it is outside the vocabulary."""
    key = normalize(tag)
    descriptor = _BY_ALIAS.get(key)
    if descriptor is not None:
        return descriptor
    return _BY_NAME.get(key)


def facet_of(name: str) -> Facet | None:
    """Facet of a canonical descriptor name, or None when the name is unknown."""
    descriptor = _BY_NAME.get(normalize(name))
    return descriptor.facet if descriptor is not None else None


def expand(name: str) -> tuple[Descriptor, ...]:
    """Neighbours of a descriptor, resolved; empty for an unknown name."""
    descriptor = _BY_NAME.get(normalize(name))
    if descriptor is None:
        return ()
    return tuple(_BY_NAME[normalize(neighbor)] for neighbor in descriptor.neighbors)


def descriptors_for(facet: Facet) -> tuple[Descriptor, ...]:
    """All descriptors of one facet, in authoring order."""
    return tuple(descriptor for descriptor in DESCRIPTORS if descriptor.facet == facet)
